// cyrb53 -- a small, fast, deterministic non-cryptographic hash.
// Not real security (see README), but it doesn't need to be. The point is
// just keeping the plaintext passphrase out of the shipped bundle.
//
// This uses plain arithmetic instead of the Web Crypto API on purpose: it
// works everywhere unconditionally, synchronously, with no "secure
// context" requirement and no risk of an API being unavailable in an
// unusual embedding context.
export function cyrb53(str: string, seed = 0): string {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  const combined = 4294967296 * (2097151 & h2) + (h1 >>> 0);
  return combined.toString(16);
}
